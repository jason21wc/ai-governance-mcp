# =============================================================================
# Unregistered-skip gate (session-302)
# =============================================================================
#
# Makes ONE observation structural instead of advisory: a skip must be registered.
# See tests/skip_allowlist.py for the root-cause reasoning and, importantly, for
# what this does NOT catch.
#
# Implemented as a session hook rather than a test because a test cannot observe
# the outcomes of the run that contains it.

_UNREGISTERED_SKIPS: list[tuple[str, str]] = []


def pytest_runtest_logreport(report):
    """Collect skip reasons as they occur.

    EXCLUDES xfail. pytest reports an xfailed test as ``outcome == "skipped"``
    with a ``wasxfail`` attribute set (verified by isolated repro: phase=call,
    ``hasattr(report, "wasxfail") is True``), so a bare ``report.skipped`` test
    swept up every xfail and failed the run for the opposite of this gate's
    purpose. Measured cost of the omission: ``pytest tests/test_doc_pointer_resolution.py``
    exited 1 with 5 passed / 1 xfailed / **zero real skips**, printing a
    misleading UNREGISTERED SKIPS banner — and the xfail in question is BACKLOG
    #325's acceptance test, so the arc's own completion proof returned red for a
    bogus reason. It went unseen because the standard command is
    ``pytest -m 'not slow'`` and that test is ``slow``, so no xfail ever reached
    this hook in a gate run.

    The distinction is the whole point: a **skip** asserts nothing and looks like
    success, which is what this gate exists to catch. An **xfail** is a declared,
    reviewed expected failure, and ``strict=True`` already fails the run if it
    starts passing — a stronger version of this same discipline, not a hole in it.
    """
    if report.skipped and not hasattr(report, "wasxfail"):
        reason = ""
        if isinstance(report.longrepr, tuple) and len(report.longrepr) == 3:
            reason = report.longrepr[2]
        else:
            reason = str(report.longrepr)
        from tests.skip_allowlist import is_registered

        if not is_registered(reason):
            _UNREGISTERED_SKIPS.append((report.nodeid, reason))


def pytest_sessionfinish(session, exitstatus):
    """Fail the run on any unregistered skip.

    A skip is the one outcome that looks like success and asserts nothing. Left
    advisory, a new one hides indefinitely — measured in session-302, where a
    stale hardcoded path silently skipped the entire retrieval benchmark for weeks
    while the suite reported green, and a guard added to fix that introduced a
    second silent-skip class the same day.
    """
    if not _UNREGISTERED_SKIPS:
        return
    print("\n\nUNREGISTERED SKIPS — a skip must be registered with a reason:")
    for nodeid, reason in _UNREGISTERED_SKIPS:
        print(f"  {nodeid}\n    {reason.strip()[:200]}")
    print(
        "\nIf the skip is correct, add an entry to tests/skip_allowlist.py saying "
        "WHY it is correct. If it is not correct, you have found a defect that "
        "would otherwise have been invisible in a green run."
    )
    session.exitstatus = 1
