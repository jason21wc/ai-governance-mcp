@pytest.fixture(autouse=True)
def isolate_home(request, tmp_path_factory, monkeypatch):
    """Point ``$HOME`` at a throwaway directory for every test.

    **Why this is autouse and global rather than per-call-site.** Six hooks in
    ``.claude/hooks/`` append to logs under ``$HOME``, and the hook tests invoke
    those hooks as real subprocesses. Isolation was therefore a choice made
    (or forgotten) at each of ~210 ``run_hook`` call sites spread across seven
    independent copies of a ``run_hook`` helper. It was forgotten most of the
    time, and the failure is silent: the test passes either way.

    Measured consequence before this fixture existed:
    ``~/.context-engine/plan-contrarian-denies.log`` held **872 lines, 865 of
    them generated by the test suite** — 7 real events buried in 99.2% noise.
    That log is the named instrument for OPERATIONS **V-012**, so a verification
    item was measuring its own test runs. The same class had already happened
    once, when a fixture overwrote the committed index with random vectors, so
    this is the second instance of "tests write to a production artifact" — a
    rule, not an incident.

    Fixing the call sites would leave the eighth copy of the helper free to
    reintroduce it. Fixing the environment removes the choice.

    **Blast radius, measured rather than assumed:** the full suite was run with
    ``HOME`` redirected before this shipped — 2710 passed, 2 failed, and both
    failures are tests that legitimately need the real home. Those two carry
    ``@pytest.mark.real_home``. If a third ever needs it, the marker is the
    honest way to say so; silently reading the real home is not.
    """
    if request.node.get_closest_marker("real_home"):
        return

    # PRESERVE READ ACCESS TO THE INDEX (session-268). This fixture exists to stop
    # tests WRITING to production telemetry under $HOME. The governance index is
    # read-only for tests — isolating it buys nothing and breaks every test that needs
    # one, because the index stopped being committed and now defaults to
    # `~/.ai-governance/index`. Symptom when this was missing: 14 tests failed on
    # `main` (but passed in the authoring worktree, which still had a leftover
    # `index/` on disk — the merge deleted it from `main`). Pin the real location
    # BEFORE $HOME moves, and only when the caller has not already chosen one.
    if not os.environ.get("AI_GOVERNANCE_INDEX_PATH"):
        real_index = (
            Path(
                os.environ.get("AI_GOVERNANCE_USER_DATA_ROOT", "~/.ai-governance")
            ).expanduser()
            / "index"
        )
        if (real_index / "global_index.json").is_file():
            monkeypatch.setenv("AI_GOVERNANCE_INDEX_PATH", str(real_index))

    home = tmp_path_factory.mktemp("home")
    (home / ".claude").mkdir(exist_ok=True)
    (home / ".context-engine").mkdir(exist_ok=True)
    monkeypatch.setenv("HOME", str(home))


# -- Reference-library write guard (#294) ------------------------------------


def _snapshot_dir(path: Path) -> dict[str, int]:
    """``{relative_posix_path: mtime_ns}`` for every file under *path*."""
    if not path.is_dir():
        return {}
    return {
        str(p.relative_to(path)): p.stat().st_mtime_ns
        for p in path.rglob("*")
        if p.is_file()
    }


def _diff_snapshots(before: dict[str, int], after: dict[str, int]) -> list[str]:
    """Paths that are new or modified in *after* relative to *before*."""
    return sorted(p for p, mtime in after.items() if before.get(p) != mtime)


@pytest.fixture(scope="session", autouse=True)
def _guard_real_reference_library():
    """Fail the run if ANY test writes to the REAL reference library.

    BACKLOG #294 defense-in-depth.  ``isolate_home`` is the primary guard
    (function-scoped, redirects ``$HOME``); this is the backstop that catches
    a regression — for instance a test that opts out via ``@pytest.mark.real_home``
    and then calls ``capture_reference``.

    The watched path is derived from the SAME resolution order as
    ``config._user_data_root()`` / ``Settings.reference_library_path``, using the
    pristine ambient env (session scope runs before any per-test monkeypatch).
    Hardcoding ``~/.ai-governance/reference-library/`` would reproduce the
    exact class of bug this guard exists to catch — two consumers resolving the
    path differently.
    """
    import pwd

    try:
        real_home = Path(pwd.getpwuid(os.getuid()).pw_dir).resolve()
    except KeyError:
        yield
        return

    ref_lib_override = os.environ.get("AI_GOVERNANCE_REFERENCE_LIBRARY_PATH")
    if ref_lib_override:
        ref_lib = Path(ref_lib_override).expanduser().resolve()
    else:
        data_root_override = os.environ.get("AI_GOVERNANCE_USER_DATA_ROOT")
        data_root = (
            Path(data_root_override).expanduser()
            if data_root_override
            else real_home / ".ai-governance"
        )
        ref_lib = data_root / "reference-library"

    before = _snapshot_dir(ref_lib)
    yield
    after = _snapshot_dir(ref_lib)
    changed = _diff_snapshots(before, after)
    assert not changed, (
        f"Test suite wrote to the REAL reference library at {ref_lib}: "
        f"{changed}.  A test bypassed isolate_home and wrote a reference-library "
        "entry.  See BACKLOG #294 / tests/test_home_isolation.py."
    )


